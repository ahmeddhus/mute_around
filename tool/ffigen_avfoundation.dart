// Generates lib/core/native/avfoundation.ffigen.dart: the few AVFoundation
// APIs the app needs to query and request macOS microphone permission
// (`AVCaptureDevice` authorization), through ffigen's Objective-C interop.
//
//   dart run tool/ffigen_avfoundation.dart
//
// Commit the output (contributors then don't need LLVM). Needs Xcode.
import 'dart:io';

import 'package:ffigen/ffigen.dart';
import 'package:logging/logging.dart';

const _sdk =
    '/Applications/Xcode.app/Contents/Developer/Platforms/MacOSX.platform/'
    'Developer/SDKs/MacOSX.sdk';

/// The only AVCaptureDevice methods bound; everything else is filtered out.
const _methods = {
  'authorizationStatusForMediaType:',
  'requestAccessForMediaType:completionHandler:',
};

Future<void> main() async {
  final root = Platform.script.resolve('../');
  Logger.root
    ..level = Level.WARNING
    ..onRecord.listen((r) => stderr.writeln('${r.level.name}: ${r.message}'));

  await FfiGenerator(
    input: Input(
      entryPoints: [
        Uri.file(
          '$_sdk/System/Library/Frameworks/AVFoundation.framework/Headers/'
          'AVCaptureDevice.h',
        ),
      ],
    ),
    output: Output(
      dart: DartOutput(
        path: root.resolve('lib/core/native/avfoundation.ffigen.dart'),
      ),
      objectiveCFile: root.resolve('native/macos_permissions/avfoundation.m'),
      preamble: '''
// Generated by tool/ffigen_avfoundation.dart from the macOS SDK's
// AVCaptureDevice.h. Do not edit by hand.
// ignore_for_file: type=lint
''',
      style: const NativeExternalBindings(
        assetId: 'package:mute_around/macos_permissions',
      ),
    ),
    objectiveC: ObjectiveC(
      externalVersions: ExternalVersions(
        macos: Versions(min: Version(13, 0, 0)),
      ),
    ),
    visitors: [
      Visitor(
        objCInterface: (node) =>
            node.isIncluded = node.originalName == 'AVCaptureDevice',
        objCMethod: (node) {
          final parent = node.parent;
          node.isIncluded =
              (parent is ObjCInterface || parent is ObjCCategory) &&
              _methods.contains(node.selector);
        },
        objCProtocol: (node) => node.isIncluded = false,
        // The two methods live in this category.
        objCCategory: (node) => node.isIncluded =
            node.originalName == 'AVCaptureDeviceAuthorization',
        enumClass: (node) {
          node.isIncluded = node.originalName == 'AVAuthorizationStatus';
          // NS_ENUM(NSInteger, ...): the size is fixed, unlike a plain C enum.
          node.silenceWarning = true;
        },
      ),
    ],
  ).generate();
}
