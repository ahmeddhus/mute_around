// Generates lib/core/native/mute_engine.ffigen.dart from the engine's C ABI.
//
//   dart run tool/ffigen.dart
//
// Run it after changing native/engine/include/mute_engine.h and commit the
// output (contributors then don't need LLVM). Needs libclang: on macOS it
// comes with Xcode, on Windows install LLVM.
import 'dart:io';

import 'package:ffigen/ffigen.dart';
import 'package:logging/logging.dart';

/// Wait-free getters, bound as FFI leaf calls (no safepoint, nanosecond cost).
const _leafFunctions = {
  'me_get_status',
  'me_get_levels',
  'me_get_stats',
  'me_abi_version',
};

Future<void> main() async {
  final root = Platform.script.resolve('../');
  Logger.root
    ..level = Level.WARNING
    ..onRecord.listen((r) => stderr.writeln('${r.level.name}: ${r.message}'));

  await FfiGenerator(
    input: Input(
      entryPoints: [root.resolve('native/engine/include/mute_engine.h')],
    ),
    output: Output(
      dart: DartOutput(
        path: root.resolve('lib/core/native/mute_engine.ffigen.dart'),
      ),
      preamble: '''
// Generated by tool/ffigen.dart from native/engine/include/mute_engine.h.
// Do not edit by hand.
// ignore_for_file: type=lint
''',
      style: const NativeExternalBindings(
        assetId: 'package:mute_around/mute_engine',
      ),
    ),
    visitors: [
      Visitor(
        func: (f) {
          f.isIncluded = f.originalName.startsWith('me_');
          if (_leafFunctions.contains(f.originalName)) f.isLeaf = true;
        },
        // `me_engine` stays opaque: Dart only ever holds a pointer to it.
        struct: (s) => s.isIncluded =
            s.originalName.startsWith('me_') && s.originalName != 'me_engine',
        unnamedEnumConstant: (c) =>
            c.isIncluded = c.originalName.startsWith('ME_'),
        macroConstant: (m) => m.isIncluded =
            m.originalName.startsWith('ME_') && m.originalName != 'ME_API',
        typealias: (t) =>
            t.isIncluded = t.originalName.startsWith('me_') ? .ifUsed : .never,
      ),
    ],
  ).generate();
}
